using GraphemeSplitterNET;
using System;
using System.IO;
using System.Net.Http;
using System.Text;

namespace GraphemeSplitterNET_Generator
{
  /// <summary>
  /// Regenerates GraphemeSplitterNET/EmbeddedUnicodeData.cs and the conformance test data.
  /// 
  ///   dotnet run --project GraphemeSplitterNET.Generator [version] [ucdFolder]
  /// 
  ///   version   : "latest" (default) or "17.0.0", "16.0.0", ...
  ///   ucdFolder : optional folder already containing the four UCD files (offline mode).
  /// </summary>
  internal class Program
  {

    private static readonly string[] Files = {
      "auxiliary/GraphemeBreakProperty.txt",
      "emoji/emoji-data.txt",
      "DerivedCoreProperties.txt",
      "auxiliary/GraphemeBreakTest.txt",
    };

    static int Main(string[] args)
    {
      string version = args.Length > 0 ? args[0] : "latest";
      string ucdFolder = args.Length > 1 ? args[1] : null;
      string root = FindRepositoryRoot();

      var texts = new string[Files.Length];
      using (var http = new HttpClient()) {
        for (int i = 0; i < Files.Length; i++) {
          if (ucdFolder != null) {
            texts[i] = File.ReadAllText(Path.Combine(ucdFolder, Path.GetFileName(Files[i])));
          }
          else {
            string url = $"https://www.unicode.org/Public/{version}/ucd/{Files[i]}";
            Console.WriteLine($"Downloading {url}");
            texts[i] = http.GetStringAsync(url).GetAwaiter().GetResult();
          }
        }
      }

      var table = new RuleParser().Parse(texts[0], texts[1], texts[2]);
      byte[] data = table.ToBytes();

      var sb = new StringBuilder();
      sb.AppendLine("// <auto-generated>");
      sb.AppendLine("// Generated by GraphemeSplitterNET.Generator from the Unicode Character Database.");
      sb.AppendLine($"// Unicode {table.UnicodeVersion}, {data.Length:N0} bytes. Do not edit by hand.");
      sb.AppendLine("// </auto-generated>");
      sb.AppendLine("namespace GraphemeSplitterNET");
      sb.AppendLine("{");
      sb.AppendLine("  internal static class EmbeddedUnicodeData");
      sb.AppendLine("  {");
      sb.AppendLine($"    public const string Version = \"{table.UnicodeVersion}\";");
      sb.AppendLine("    public const string Data =");
      string base64 = Convert.ToBase64String(data);
      for (int i = 0; i < base64.Length; i += 120) {
        string chunk = base64.Substring(i, Math.Min(120, base64.Length - i));
        sb.Append("      \"").Append(chunk).Append('"');
        sb.AppendLine(i + 120 < base64.Length ? " +" : ";");
      }
      sb.AppendLine("  }");
      sb.AppendLine("}");

      string target = Path.Combine(root, "GraphemeSplitterNET", "EmbeddedUnicodeData.cs");
      File.WriteAllText(target, sb.ToString(), new UTF8Encoding(false));
      Console.WriteLine($"Wrote {target} (Unicode {table.UnicodeVersion}, {data.Length:N0} bytes)");

      string testData = Path.Combine(root, "GraphemeSplitterNET.Tests", "Data", "GraphemeBreakTest.txt");
      Directory.CreateDirectory(Path.GetDirectoryName(testData));
      File.WriteAllText(testData, texts[3], new UTF8Encoding(false));
      Console.WriteLine($"Wrote {testData}");
      return 0;
    }

    private static string FindRepositoryRoot()
    {
      var dir = new DirectoryInfo(AppContext.BaseDirectory);
      while (dir != null && !File.Exists(Path.Combine(dir.FullName, "GraphemeSplitterNET.sln"))) {
        dir = dir.Parent;
      }
      if (dir == null) throw new InvalidOperationException("GraphemeSplitterNET.sln not found.");
      return dir.FullName;
    }
  }
}
